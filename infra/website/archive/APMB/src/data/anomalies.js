export const getGroupedAnomalies = () => {
  const grouped = {};
  
  // 1. 등급별로 빈 배열 생성 (순서 보장을 위해 RISK_LEVELS 키 사용)
  Object.keys(RISK_LEVELS).forEach(risk => {
    grouped[risk] = [];
  });

  // 2. 사상체 분류 및 정렬
  ANOMALIES.forEach(doc => {
    if (grouped[doc.risk]) {
      grouped[doc.risk].push(doc);
    }
  });

  // 3. 각 등급 내부에서 ID 뒤 4자리로 오름차순 정렬
  Object.keys(grouped).forEach(risk => {
    grouped[risk].sort((a, b) => {
      // ID 형식 "XX-00-XX-1234" 에서 마지막 1234만 추출
      const numA = parseInt(a.id.split('-').pop());
      const numB = parseInt(b.id.split('-').pop());
      return numA - numB; // 오름차순
    });
  });

  return grouped;
};